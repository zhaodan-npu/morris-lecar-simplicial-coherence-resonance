"""Redraw the two CV panels without changing estimates or selection rules."""

import csv
import hashlib
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib import font_manager
from matplotlib.lines import Line2D
import numpy as np

from analyze_comment2 import ALPHAS, COLORS, LABELS, MARKERS, MIN_SPIKES

HERE = Path(__file__).resolve().parent
OUT = HERE / "analysis"
FIG = HERE / "figures"
DISPLAY = {
    "control": "Pairwise (weak coupling)",
    "matched_pairwise": "Pairwise (strength-matched)",
    "higher_order": "Simplicial",
}


def read_data():
    with (OUT / "curves.csv").open(encoding="utf-8", newline="") as f:
        rows = []
        for raw in csv.DictReader(f):
            row = dict(raw)
            for key in ("alpha", "Dv", "CV_mean", "CV_ci_low", "CV_ci_high", "mean_spike_count"):
                row[key] = float(row[key])
            for key in ("valid_cv_count", "total_paths"):
                row[key] = int(row[key])
            assert row["eligible_for_minimum"] in ("True", "False")
            row["eligible_for_minimum"] = row["eligible_for_minimum"] == "True"
            assert row["eligible_for_minimum"] == (
                np.isfinite(row["CV_mean"]) and row["mean_spike_count"] >= MIN_SPIKES)
            rows.append(row)
    assert len(rows) == len({(r["alpha"], r["label"], r["Dv"]) for r in rows}) == 120
    summary = json.loads((OUT / "summary.json").read_text(encoding="utf-8"))
    for best in summary["best"]:
        group = [r for r in rows if r["alpha"] == best["alpha"] and
                 r["label"] == best["label"] and r["eligible_for_minimum"]]
        actual = min(group, key=lambda r: r["CV_mean"])
        assert actual["Dv"] == best["Dv_star"]
        assert np.isclose(actual["CV_mean"], best["CV_star"], rtol=0, atol=1e-12)
    return rows


def write_low_activity_table(rows):
    low = sorted((r for r in rows if not r["eligible_for_minimum"]),
                 key=lambda r: (r["alpha"], LABELS.index(r["label"]), r["Dv"]))
    assert len(low) == 10 and sum(np.isfinite(r["CV_mean"]) for r in low) == 9
    lines = [
        "% Generated by redraw_comment2_cv.py from analysis/curves.csv.",
        "% Requires graphicx (for the companion figure) and booktabs.",
        r"\begin{table}[!htbp]",
        r"\centering\small",
        r"\caption{Low-activity results omitted from Fig.~\ref{fig:coupling_control_direct}",
        r"and excluded from minimum selection by the unchanged requirement of at least",
        r"1000 mean total network spikes in the statistical window. CV averages",
        r"include only trajectories with a defined CV. A dash denotes an undefined",
        r"mean; it is not zero. Low CV values based on sparse activity should not",
        r"be interpreted as evidence of coherent firing.}",
        r"\label{tab:low_activity_direct}",
        r"\begin{tabular}{@{}clrrrr@{}}",
        r"\toprule",
        r"$\alpha$ & Condition & $D_v$ & CV & Defined CVs & Mean spikes \\",
        r"\midrule",
    ]
    for r in low:
        cv = f"{r['CV_mean']:.4f}" if np.isfinite(r["CV_mean"]) else "--"
        lines.append(f"{r['alpha']:.1f} & {DISPLAY[r['label']]} & {r['Dv']:g} & "
                     f"{cv} & {r['valid_cv_count']}/{r['total_paths']} & "
                     f"{r['mean_spike_count']:.4g} " + r"\\")
    lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}"])
    (HERE / "comment2_low_activity_table.tex").write_text("\n".join(lines) + "\n", encoding="ascii")
    return low


def plot_panels(rows):
    font = font_manager.findfont("Times New Roman", fallback_to_default=False)
    plt.rcParams.update({
        "font.family": "Times New Roman", "font.size": 16,
        "mathtext.fontset": "custom", "mathtext.rm": "Times New Roman",
        "mathtext.it": "Times New Roman:italic", "mathtext.bf": "Times New Roman:bold",
        "axes.labelsize": 20, "xtick.labelsize": 16, "ytick.labelsize": 16,
        "legend.fontsize": 16, "axes.linewidth": 1.5,
        "xtick.direction": "in", "ytick.direction": "in",
        "xtick.major.width": 1.3, "ytick.major.width": 1.3,
        "xtick.minor.width": 1, "ytick.minor.width": 1,
        "xtick.major.size": 6, "ytick.major.size": 6,
        "legend.frameon": False, "pdf.fonttype": 42, "ps.fonttype": 42,
    })
    records = []
    for alpha in ALPHAS:
        fig, ax = plt.subplots(figsize=(5.4, 4.1))
        fig.subplots_adjust(left=.16, right=.97, bottom=.18, top=.94)
        handles = []
        plotted, incomplete = [], []
        for label in LABELS:
            group = sorted((r for r in rows if r["alpha"] == alpha and r["label"] == label),
                           key=lambda r: r["Dv"])
            assert len(group) == 20
            x = np.array([r["Dv"] for r in group])
            y = np.array([r["CV_mean"] for r in group])
            eligible = np.array([r["eligible_for_minimum"] for r in group])
            complete = np.array([r["valid_cv_count"] == r["total_paths"] for r in group])
            color, marker = COLORS[label], MARKERS[label]
            ls = "--" if label == "control" else "-"
            # Keep excluded points as NaNs so no line crosses an omitted gap.
            ax.plot(x, np.where(eligible, y, np.nan), color=color, ls=ls, lw=2.2, zorder=2)
            for mask, fill in ((eligible & complete, color), (eligible & ~complete, "white")):
                ax.plot(x[mask], y[mask], ls="none", marker=marker, ms=5.8,
                        mfc=fill, mec=color, mew=1.2, zorder=4)
            lo = np.array([r["CV_ci_low"] for r in group])
            hi = np.array([r["CV_ci_high"] for r in group])
            assert np.all(np.isfinite(lo[eligible])) and np.all(lo[eligible] <= hi[eligible])
            ax.vlines(x[eligible], lo[eligible], hi[eligible], color=color, lw=1.1, zorder=3)
            ax.plot(x[eligible], lo[eligible], "_", color=color, ms=5)
            ax.plot(x[eligible], hi[eligible], "_", color=color, ms=5)
            handles.append(Line2D([], [], color=color, ls=ls, lw=2.2,
                                  marker=marker, ms=5.8, label=DISPLAY[label]))
            plotted.extend(dict(label=label, Dv=r["Dv"], CV_mean=r["CV_mean"],
                                valid_cv_count=r["valid_cv_count"])
                           for r in group if r["eligible_for_minimum"])
            incomplete.extend(dict(label=label, Dv=r["Dv"], valid_cv_count=r["valid_cv_count"],
                                   total_paths=r["total_paths"])
                              for r in group if r["eligible_for_minimum"] and
                              r["valid_cv_count"] < r["total_paths"])
        ax.set_xscale("log")
        ax.set_xlim(.035, 10.5)
        ax.set_xticks([.04, .1, .3, 1, 4, 9], ["0.04", "0.10", "0.30", "1", "4", "9"])
        ax.set_ylim(0, 2.1)
        ax.set_yticks([0, .5, 1, 1.5, 2])
        ax.set_xlabel(r"$D_v$")
        ax.set_ylabel("CV")
        ax.minorticks_on()
        ax.tick_params(which="both", top=True, right=True)
        alpha_text = ax.text(.045, .93, rf"$\alpha={alpha:.1f}$", transform=ax.transAxes,
                             va="top", fontsize=18)
        legend = ax.legend(handles=handles, loc="upper right", borderaxespad=.25,
                           handlelength=1.5, handletextpad=.5, labelspacing=.25)
        fig.canvas.draw()
        renderer = fig.canvas.get_renderer()
        assert not alpha_text.get_window_extent(renderer).overlaps(legend.get_window_extent(renderer))
        for text in (ax.xaxis.label, ax.yaxis.label, *ax.get_xticklabels(), *ax.get_yticklabels()):
            box = text.get_window_extent(renderer)
            assert box.x0 >= 0 and box.y0 >= 0 and box.x1 <= fig.bbox.x1 and box.y1 <= fig.bbox.y1
        stem = f"fig_R1_cv_alpha{str(alpha).replace('.', '')}_revised"
        for suffix in ("pdf", "eps", "png"):
            fig.savefig(FIG / f"{stem}.{suffix}", dpi=450)
        plt.close(fig)
        records.append(dict(alpha=alpha, stem=stem, plotted=plotted, incomplete=incomplete))
    assert [len(r["plotted"]) for r in records] == [58, 52]
    assert [(r["Dv"], r["valid_cv_count"]) for r in records[1]["incomplete"]] == [
        (.09, 2143), (.12, 4047), (.16, 4311)]
    return font, records


def main():
    inputs = [OUT / "curves.csv", OUT / "summary.json", OUT / "input_manifest.json"]
    before = {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in inputs}
    rows = read_data()
    low = write_low_activity_table(rows)
    font, panels = plot_panels(rows)
    assert before == {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in inputs}
    report = dict(input_hashes=before, source_data_unchanged=True, all_six_minima_unchanged=True,
                  activity_rule=f"mean total network spikes >= {MIN_SPIKES}",
                  smoothing=False, optimum_overlays=False, panel_letters=False,
                  legend_labels=DISPLAY, low_activity_table_rows=len(low),
                  low_activity_finite_cv_count=sum(bool(np.isfinite(r["CV_mean"])) for r in low),
                  font=font, panels=panels)
    (OUT / "cv_redraw_verification.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps({k: v for k, v in report.items() if k != "panels"}, indent=2))


if __name__ == "__main__":
    main()
